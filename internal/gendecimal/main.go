// Command gendecimal generates result-preserving delegates from pinned upstream sources.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func render(n ast.Node) string {
	var b bytes.Buffer
	must(printer.Fprint(&b, token.NewFileSet(), n))
	return b.String()
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func main() {
	if len(os.Args) != 4 {
		panic("usage: gendecimal package source-directory upstream-import")
	}
	pkg, source, upstream := os.Args[1], os.Args[2], os.Args[3]
	entries, err := os.ReadDir(source)
	must(err)
	imports := map[string]string{}
	var out strings.Builder
	for _, entry := range entries {
		if !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(source, entry.Name()), nil, 0)
		must(err)
		for _, im := range f.Imports {
			path, err := strconv.Unquote(im.Path.Value)
			must(err)
			name := filepath.Base(path)
			if im.Name != nil {
				name = im.Name.Name
			}
			imports[name] = path
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || !fn.Name.IsExported() {
				continue
			}
			name := fn.Name.Name
			if strings.Contains(name, "Marshal") || name == "String" || name == "Format" || name == "Append" || name == "AppendText" || name == "AppendBinary" || name == "Scan" || name == "Value" {
				continue
			}
			receiver := ""
			if fn.Recv != nil {
				if render(fn.Recv.List[0].Type) != "Decimal" {
					continue
				}
				receiver = "(d Decimal) "
			}
			sig := render(fn.Type)
			if receiver == "" && !strings.Contains(sig, "Decimal") {
				continue
			}
			params, args := []string{}, []string{}
			if fn.Type.Params != nil {
				for _, field := range fn.Type.Params.List {
					typ := render(field.Type)
					for _, id := range field.Names {
						params = append(params, id.Name+" "+typ)
						arg := id.Name
						if typ == "Decimal" {
							arg += ".Decimal"
						}
						if typ == "...Decimal" {
							arg = "unwrap(" + arg + ")..."
						}
						args = append(args, arg)
					}
				}
			}
			results, values, returns := []string{}, []string{}, []string{}
			if fn.Type.Results != nil {
				for _, field := range fn.Type.Results.List {
					count := max(1, len(field.Names))
					for range count {
						typ := render(field.Type)
						results = append(results, typ)
						value := fmt.Sprintf("r%d", len(values))
						values = append(values, value)
						if typ == "Decimal" {
							value = "Decimal{" + value + "}"
						}
						returns = append(returns, value)
					}
				}
			}
			target := "upstream." + name
			if receiver != "" {
				target = "d.Decimal." + name
			}
			resultSig := ""
			if len(results) > 0 {
				resultSig = "(" + strings.Join(results, ",") + ")"
			}
			fmt.Fprintf(&out, "func %s%s(%s) %s {", receiver, name, strings.Join(params, ","), resultSig)
			if len(values) > 0 {
				fmt.Fprintf(&out, "%s := ", strings.Join(values, ","))
			}
			fmt.Fprintf(&out, "%s(%s)\n", target, strings.Join(args, ","))
			if len(values) > 0 {
				fmt.Fprintf(&out, "return %s\n", strings.Join(returns, ","))
			}
			out.WriteString("}\n")
		}
	}
	var header strings.Builder
	fmt.Fprintf(&header, "// Code generated by internal/gendecimal; DO NOT EDIT.\npackage %s\nimport upstream %q\n", pkg, upstream)
	for name, path := range imports {
		if strings.Contains(out.String(), name+".") {
			fmt.Fprintf(&header, "import %s %q\n", name, path)
		}
	}
	if pkg == "bigdecimal" {
		header.WriteString("type CmpResult = upstream.CmpResult\ntype RoundingMode = upstream.RoundingMode\ntype Payload = upstream.Payload\nconst (ToNearestEven = upstream.ToNearestEven; ToNearestAway = upstream.ToNearestAway; ToZero = upstream.ToZero; AwayFromZero = upstream.AwayFromZero; ToNegativeInf = upstream.ToNegativeInf; ToPositiveInf = upstream.ToPositiveInf)\n")
	}
	header.WriteString("func unwrap(values []Decimal) []upstream.Decimal { result:=make([]upstream.Decimal,len(values)); for i,v:=range values {result[i]=v.Decimal}; return result }\n")
	data, err := format.Source([]byte(header.String() + out.String()))
	must(err)
	must(os.MkdirAll(pkg, 0755))
	must(os.WriteFile(filepath.Join(pkg, "operations_gen.go"), data, 0644))
}
